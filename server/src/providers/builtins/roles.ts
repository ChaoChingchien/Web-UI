/** 创建内置角色（首次启动时调用）
 *  内置角色不预设 provider（由用户在 Team 配置或聊天中自行选择模型），
 *  `defaultProviderId` 字段保留仅供历史记录与类型检查，实际不再写入 DB。 */
export function createBuiltinRoles(): AIRole[] {
  const now = new Date().toISOString();
  return builtinRoleTemplates.map((t) => ({
    id: t.id,
    name: t.name,
    icon: t.icon,
    system_prompt: t.systemPrompt,
    provider_id: '',
    config: { temperature: 0.7, max_tokens: 4096 },
    is_custom: false,
    created_at: now,
    updated_at: now,
  }));
}
